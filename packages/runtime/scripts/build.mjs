// Build @mithril-lang/runtime: one plain ESM module that runs the Mithril
// language with no nbb, kbb or Kotoba toolchain at consume time.
//
// 1. Mirror every .cljk under src/ and vendor/src/ to build/shadow-src/*.cljc
//    (shadow-cljs reads .cljs/.cljc/.clj only; a sibling .cljc wins).
// 2. Generate mithril.runtime.build-info (version, source sha, embedded lib text).
// 3. shadow-cljs release → dist/runtime.mjs, then record its SHA-256.
//
//   node packages/runtime/scripts/build.mjs [--check]
//
// --check rebuilds into a temp dir and fails if dist/ differs (reproducibility).
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(pkg, '../..');
const shim = join(pkg, 'build/shadow-src');
const check = process.argv.includes('--check');
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim();
// Sources that feed the bundle must be committed, so source-sha names them exactly.
const dirty = git('status', '--porcelain', '--', 'src', 'vendor/src', 'lib/app', 'packages/runtime/src');
if (dirty && !process.env.MITHRIL_RUNTIME_ALLOW_DIRTY) throw new Error('Runtime sources have uncommitted changes:\n' + dirty);
const sourceSha = git('log', '-1', '--format=%H', '--', 'src', 'vendor/src', 'lib/app', 'packages/runtime/src');

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}
rmSync(shim, { recursive: true, force: true });
let mirrored = 0;
for (const root of [join(repo, 'src'), join(repo, 'vendor/src')]) {
  for (const p of walk(root)) {
    if (!p.endsWith('.cljk') || existsSync(p.replace(/\.cljk$/, '.cljc'))) continue;
    const target = join(shim, relative(root, p).replace(/\.cljk$/, '.cljc'));
    mkdirSync(dirname(target), { recursive: true });
    cpSync(p, target);
    mirrored++;
  }
}

const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
const libText = readFileSync(join(repo, 'lib/app/agent-loop-v1.mith'), 'utf8');
mkdirSync(join(shim, 'mithril/runtime'), { recursive: true });
writeFileSync(join(shim, 'mithril/runtime/build_info.cljs'), `(ns mithril.runtime.build-info)
;; Generated by packages/runtime/scripts/build.mjs. Do not edit.
(def version ${JSON.stringify(version)})
(def source-sha ${JSON.stringify(sourceSha)})
(def app-agent-loop-v1 ${JSON.stringify(libText)})
`);

const out = check ? join(pkg, 'build/check') : join(pkg, 'dist');
rmSync(join(pkg, 'build/esm'), { recursive: true, force: true });
const build = spawnSync(join(pkg, 'node_modules/.bin/shadow-cljs'), ['release', 'runtime'], { cwd: pkg, stdio: 'inherit' });
if (build.status !== 0) process.exit(build.status ?? 1);

const bundle = readFileSync(join(pkg, 'build/esm/runtime.js'));
mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'runtime.mjs'), bundle);
const manifest = { name: '@mithril-lang/runtime', version, sourceSha, sha256: sha256(bundle), bytes: bundle.length, mirroredCljk: mirrored };
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
if (check) {
  const committed = readFileSync(join(pkg, 'dist/runtime.mjs'));
  if (sha256(committed) !== manifest.sha256) throw new Error(`dist/runtime.mjs is not reproducible: committed ${sha256(committed)}, rebuilt ${manifest.sha256}`);
}
console.log(JSON.stringify(manifest));
